// Rebuilds sprites.js (the default art, as data URLs) from sprites/src/*.png.
//   node tools/build_sprites.js
//
// - Player frames are trimmed to one shared box, so swapping frames never
//   moves the character.
// - Obstacles are trimmed tight, so their bottom edge sits on the ground.
const fs = require('fs');
const path = require('path');
const P = require('./png');

const root = path.join(__dirname, '..');
const src = (n) => P.decode(fs.readFileSync(path.join(root, 'sprites/src', n + '.png')));
const url = (img) => 'data:image/png;base64,' + P.encode(img).toString('base64');

// Player: crop all frames to the union of their bounding boxes
const frameNames = ['run1', 'run2', 'jump', 'dead'];
const frames = frameNames.map(src);
const boxes = frames.map((f) => P.bbox(f));
const x0 = Math.min(...boxes.map((b) => b.x0)), x1 = Math.max(...boxes.map((b) => b.x1));
const y0 = Math.min(...boxes.map((b) => b.y0)), y1 = Math.max(...boxes.map((b) => b.y1));
const player = {};
frameNames.forEach((n, i) => { player[n] = url(P.crop(frames[i], x0, y0, x1 - x0 + 1, y1 - y0 + 1)); });
console.log('player', (x1 - x0 + 1) + 'x' + (y1 - y0 + 1));

// Obstacles: [file, height range in px, weight]
const trim = (n) => { const img = src(n); const b = P.bbox(img); return P.crop(img, b.x0, b.y0, b.x1 - b.x0 + 1, b.y1 - b.y0 + 1); };
const OBSTACLES = [['grill-kettle', [26, 62], 1], ['grill-gas', [26, 62], 1], ['ketchup', [24, 40], 0.7]];
const SPECIALS = [['bun-tower', [48, 55], 1], ['hot-dog-pile', [26, 30], 1]];
const list = (items) => items.map(([n, height, weight]) => {
  const img = trim(n);
  console.log(n, img.w + 'x' + img.h);
  return { src: url(img), height, weight };
});

let js = '// Generated by tools/build_sprites.js from sprites/src/*.png. Do not edit by hand.\n';
js += 'export const DEFAULT_PLAYER = ' + JSON.stringify(player, null, 2) + ';\n';
js += 'export const DEFAULT_OBSTACLES = ' + JSON.stringify(list(OBSTACLES), null, 2) + ';\n';
js += 'export const DEFAULT_SPECIALS = ' + JSON.stringify(list(SPECIALS), null, 2) + ';\n';
fs.writeFileSync(path.join(root, 'sprites.js'), js);
